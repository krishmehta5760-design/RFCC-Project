"""Assembles the upload package (max 50 MB) on the Desktop:
   SIW_Filter_Submission/1_Course_Project_Files, 2_Thesis, 3_Research_Paper  (+ a .zip of the same)
Run with any Python 3:  python make_submission.py"""
import os, shutil, subprocess

ROOT = os.path.dirname(os.path.abspath(__file__))
DEST = os.path.join(os.path.dirname(ROOT), "SIW_Filter_Submission")
P1, P2, P3 = (os.path.join(DEST, n) for n in ("1_Course_Project_Files", "2_Thesis", "3_Research_Paper"))
LIMIT_MB = 50


def word_pdf(docx, pdf):
    if os.path.exists(pdf) and os.path.getmtime(pdf) >= os.path.getmtime(docx):
        return
    ps = (f"$w = New-Object -ComObject Word.Application; $w.Visible = $false; $d = $w.Documents.Open('{docx}', $false, $true); "
          f"$d.ExportAsFixedFormat('{pdf}', 17); $d.Close($false); try {{ $w.Quit() }} catch {{}}")
    subprocess.run(["powershell", "-NoProfile", "-Command", ps], check=False)


def copy(src_rel, dst_dir, dst_rel=None):
    src = os.path.join(ROOT, src_rel); dst = os.path.join(dst_dir, dst_rel or src_rel)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.isdir(src):
        shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc", "~$*"), dirs_exist_ok=True)
    else:
        shutil.copy2(src, dst)


def size_mb(path):
    return sum(os.path.getsize(os.path.join(dp, f)) for dp, _, fs in os.walk(path) for f in fs) / 2**20


# fresh output folder
if os.path.exists(DEST):
    shutil.rmtree(DEST)
os.makedirs(DEST)

# PDFs of the Word documents (made with the installed MS Word)
word_pdf(os.path.join(ROOT, "05_Report", "SIW_Filter_Xband_Project_Report.docx"),
         os.path.join(ROOT, "05_Report", "SIW_Filter_Xband_Project_Report.pdf"))

# ---------------- 1: course project files (no raw simulation data: it is regenerated by the scripts)
for f in ["README.md", "00_IMPLEMENTATION_PLAN.md", "01_WHAT_AND_WHY.md", "RESULTS_AND_CONCLUSIONS.md",
          "PRESENTATION_GUIDE.md", "make_submission.py", "01_Base_Paper", "02_Design_Calculations"]:
    copy(f, P1)
sim = os.path.join(ROOT, "03_openEMS_Simulation")
for f in sorted(os.listdir(sim)):
    if f.endswith(".py"):
        copy(os.path.join("03_openEMS_Simulation", f), P1)
for f in ["plots", "tables", "touchstone", "00_IMPORTANT_PLOTS", "README_WHAT_IS_WHAT.md"]:
    copy(os.path.join("04_Results", f), P1)
for f in ["SIW_Filter_Xband_Project_Report.docx", "SIW_Filter_Xband_Project_Report.pdf", "make_report.py",
          "docx_helpers.py", "make_presentation_guide_docx.py", "PRESENTATION_GUIDE.docx"]:
    copy(os.path.join("05_Report", f), P1)
for f in ["SIW_Filter_Presentation.pptx", "PRESENTATION_SCRIPT.docx", "PRESENTATION_SCRIPT.md", "make_presentation.py",
          "make_presentation_figures.py", "figs"]:
    copy(os.path.join("06_Presentation", f), P1)
copy(os.path.join("07_Thesis", "make_thesis.py"), P1)
copy(os.path.join("08_Research_Paper", "make_paper_figures.py"), P1)

# ---------------- 2: thesis
for f in ["SIW_Filter_Xband_Thesis.pdf", "SIW_Filter_Xband_Thesis.docx"]:
    copy(os.path.join("07_Thesis", f), P2, f)

# ---------------- 3: research paper (PDF + complete LaTeX source)
copy(os.path.join("08_Research_Paper", "SIW_Filter_IEEE_Paper.pdf"), P3, "SIW_Filter_IEEE_Paper.pdf")
copy(os.path.join("08_Research_Paper", "SIW_Filter_IEEE_Paper.tex"), P3, os.path.join("LaTeX_source", "SIW_Filter_IEEE_Paper.tex"))
copy(os.path.join("08_Research_Paper", "figs"), P3, os.path.join("LaTeX_source", "figs"))

with open(os.path.join(DEST, "README.txt"), "w", encoding="utf-8") as fh:
    fh.write("SIW band-pass filter at X-band (openEMS) - course project submission\n\n"
             "1_Course_Project_Files  all scripts, results (plots, tables, Touchstone .s2p), report, slides,\n"
             "                        presentation script and the base paper. Start with README.md.\n"
             "                        The raw simulation data (about 15 MB) is not included; run\n"
             "                        03_openEMS_Simulation/run_all.py to regenerate it.\n"
             "2_Thesis                full thesis (PDF and editable Word file)\n"
             "3_Research_Paper        IEEE conference-format paper (PDF) with its LaTeX source\n"
             "                        (compile LaTeX_source/SIW_Filter_IEEE_Paper.tex with pdflatex twice)\n")

zp = shutil.make_archive(DEST, "zip", DEST)
total = size_mb(DEST)
for p in (P1, P2, P3):
    print(f"{os.path.basename(p):26s} {size_mb(p):6.1f} MB")
print(f"{'TOTAL (folders)':26s} {total:6.1f} MB   (limit {LIMIT_MB} MB)  -> {'OK' if total < LIMIT_MB else 'TOO BIG'}")
print(f"{'zip file':26s} {os.path.getsize(zp)/2**20:6.1f} MB   {zp}")
